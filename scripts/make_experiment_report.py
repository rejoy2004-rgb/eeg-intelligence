"""Write docs/EXPERIMENTS.md from a saved experiment folder so the documented numbers cannot drift from the data.

Usage: python scripts/make_experiment_report.py [run_name]   (default: final_v1)
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
run = sys.argv[1] if len(sys.argv) > 1 else "final_v1"
d = ROOT / "outputs" / run
summary = json.loads((d / "summary.json").read_text(encoding="utf-8"))
res = pd.read_csv(d / "results_per_split.csv")
cfg = summary["config"]
NAMES = {"majority": "Majority class (floor)", "logreg": "Band power + logistic regression",
         "csp_lda": "CSP + LDA", "cnn": "Spatial-image CNN"}
ORDER = ["majority", "logreg", "csp_lda", "cnn"]
PROTO = {"cross_session": "Protocol A - same participant, unseen session (train T → test E)",
         "loso": "Protocol B - unseen participant (leave-one-subject-out)"}


def fmt(x, n=3):
    return "n/a" if pd.isna(x) else f"{x:.{n}f}"


lines = []
w = lines.append
w("# Experiments and results")
w("")
w(f"*This file is generated by `scripts/make_experiment_report.py` from `outputs/{run}/` — do not edit the numbers by hand.*")
w("")
w("## Status of the results")
w("")
w(f"* Run name: **{summary['run_name']}**, status: **{summary['status']}**, created {summary['created_utc']} (UTC).")
w(f"* Note recorded with the run: {summary['notes']}")
w("* Honest history: before this run a *functional* smoke run (subjects 1–2, cross-session protocol, all four models) was executed to check "
  "that the code ran end to end. Its numbers were seen. **No configuration value, model or protocol was changed afterwards**; the only code edits "
  "after the smoke run were behaviour-preserving: test fixtures, an index-array fix in `TrialSet.select` (boolean masks behave as before), a `.detach()` call in the "
  "training loop, and silenced MNE log output. The final run is the first and only run of the "
  "complete protocol. The configuration is the one stored in `outputs/" + run + "/summary.json`.")
w("* Hyper-parameters that are *selected* (the logistic-regression C) were chosen by grouped inner cross-validation inside each training set. "
  "CNN architecture, learning rate, epochs, band definitions, epoch window and rejection thresholds were fixed a priori in `configs/default.yaml`.")
w(f"* Software: {json.dumps(summary['software'])}")
w("")
w("## Data used")
w("")
w(f"* BCI Competition IV 2a, all 9 participants, both sessions, left-hand vs right-hand imagery only "
  f"(classes 3 and 4 are excluded as outside the task and are counted, not hidden).")
w(f"* **{summary['n_trials_total']} trials** after rejection; class counts {summary['class_counts']} (0 = left, 1 = right).")
rej = pd.read_csv(d / "rejected_trials.csv")
w(f"* Rejected left/right trials: **{len(rej)}** — reasons: {rej['reason'].value_counts().to_dict()}. Full list: `outputs/{run}/rejected_trials.csv`.")
w(f"* Epoch: {cfg['preprocessing']['epoch_tmin_s']}–{cfg['preprocessing']['epoch_tmax_s']} s after cue onset; band-pass "
  f"{cfg['preprocessing']['bandpass_hz']} Hz (CSP: {cfg['preprocessing']['csp_bandpass_hz']} Hz); features: log mean PSD in {cfg['features']['bands_hz']}.")
w(f"* Spatial grid {cfg['spatial']['grid_size']}×{cfg['spatial']['grid_size']}, {cfg['spatial']['interpolation']} interpolation, montage `{cfg['spatial']['montage']}`.")
w("")
for protocol, g in res.groupby("protocol"):
    w(f"## {PROTO[protocol]}")
    w("")
    n_sub = g["test_subject"].nunique()
    if protocol == "cross_session":
        w("Question answered: *can a model calibrated on one person's first session be used on the same person on another day?* "
          "Training uses only that participant's session T (the last run of T is the CNN's validation set; logistic-regression C is chosen by "
          "run-grouped 5-fold CV); the test set is that participant's session E. Each model therefore trains on roughly 110–140 trials (the CNN on about one run fewer, which is held out for validation).")
    else:
        w("Question answered: *does a model transfer to a participant it has never seen?* For every held-out participant, all their trials "
          "(both sessions) are held out of training **and** model selection; the CNN is validated on two other whole participants "
          "(the next two IDs, a fixed rule); logistic-regression C is chosen by subject-grouped 5-fold CV inside the 8 training participants.")
    w("")
    w(f"Evaluated participants: **{n_sub}**; training participants per fold: {'1 (their own session T)' if protocol == 'cross_session' else '8'}.")
    w("")
    w("### Mean ± standard deviation across participants")
    w("")
    w("| Model | Balanced accuracy | Accuracy | F1 | ROC-AUC | Precision | Recall (right) | Specificity (left) |")
    w("|---|---|---|---|---|---|---|---|")
    for m in ORDER:
        gm = g[g["model"] == m]
        cells = []
        for metric in ("balanced_accuracy", "accuracy", "f1", "roc_auc", "precision", "recall", "specificity"):
            v = gm[metric].dropna()
            cells.append("n/a" if v.empty else f"{v.mean():.3f} ± {v.std(ddof=1):.3f}" if len(v) > 1 else f"{v.mean():.3f}")
        w(f"| {NAMES[m]} | " + " | ".join(cells) + " |")
    w("")
    w("(n/a = undefined: the majority baseline produces no scores, hence no ROC-AUC.)")
    w("")
    w("### Per-participant balanced accuracy")
    w("")
    pv = g.pivot(index="test_subject", columns="model", values="balanced_accuracy")
    nt = g[g["model"] == "cnn"].set_index("test_subject")["n_test"]
    thr = g[g["model"] == "cnn"].set_index("test_subject")["chance_threshold_p05"]
    w("| Participant | n test | " + " | ".join(NAMES[m] for m in ORDER) + " | accuracy needed to beat chance (p<0.05, one-sided binomial) |")
    w("|---|---|" + "---|" * len(ORDER) + "---|")
    for s in pv.index:
        w(f"| S{s:02d} | {nt[s]} | " + " | ".join(fmt(pv.loc[s, m]) for m in ORDER) + f" | {thr[s]:.3f} |")
    w("")
    agg = summary["aggregate"][protocol]
    w("### Participants whose accuracy exceeds the chance threshold (p<0.05, one-sided binomial, uncorrected)")
    w("")
    for m in ORDER:
        gm = g[g["model"] == m]
        above = int((gm["accuracy"] > gm["chance_threshold_p05"]).sum())
        best = gm.loc[gm["accuracy"].idxmax()]
        w(f"* {NAMES[m]}: {above} of {len(gm)} participants (best: S{int(best['test_subject']):02d} at {best['accuracy']:.3f}; "
          f"mean without the best participant: {gm[gm['test_subject'] != best['test_subject']]['balanced_accuracy'].mean():.3f})")
    w("")
    w("### Pooled confusion matrices (rows = true class, columns = predicted; left, right)")
    w("")
    for m in ORDER:
        cm = agg[m]["pooled_confusion_matrix"]
        w(f"* {NAMES[m]}: TN={cm[0][0]}, FP={cm[0][1]}, FN={cm[1][0]}, TP={cm[1][1]}")
    w("")
    w("### Paired comparisons of balanced accuracy across participants (Wilcoxon signed-rank, two-sided, exact)")
    w("")
    w("| Comparison | mean difference | p-value | pairs |")
    w("|---|---|---|---|")
    for k, v in agg["paired_comparisons"].items():
        a, b = k.split("_vs_")
        w(f"| {NAMES[a]} − {NAMES[b]} | {v['mean_difference_balanced_accuracy']:+.3f} | {fmt(v['wilcoxon_p_two_sided'])} | {v['n_pairs']} |")
    w("")
    w("With 9 participants the smallest possible two-sided exact p-value is 0.0039, and these tests were not corrected for the three comparisons "
      "per protocol. Treat them as indicative, not as proof.")
    w("")
    cn = g[g["model"] == "cnn"]
    w(f"CNN training details: median best epoch {cn['info_best_epoch'].median():.0f}, median epochs run {cn['info_epochs_run'].median():.0f} "
      f"(early stopping, patience {cfg['models']['cnn']['patience']}).")
    lr = g[g["model"] == "logreg"]
    w(f"Selected logistic-regression C values: {sorted(lr['info_best_C'].dropna().tolist())}.")
    w("")
w("## How to read these numbers")
w("")
w("* Chance level for balanced accuracy is 0.5. With ~110–280 test trials per participant, an accuracy needs to be roughly 0.55–0.59 "
  "to be distinguishable from chance for *that participant* (last column above, one-sided binomial test, p<0.05, uncorrected).")
w("* The two protocols are different questions. Protocol A numbers must not be presented as evidence of cross-participant generalisation, "
  "and vice versa.")
w("* The spread between participants (std column; best vs worst participant) is as important as the mean.")
w("* No comparison with published results is made: published BCI Competition IV 2a results mostly concern the 4-class problem with different "
  "splits and metrics (e.g. Cohen's kappa), so they are not comparable with the binary balanced-accuracy numbers above.")
w("* The CNN did **not** outperform the classical baselines in this experiment. Possible reasons (hypotheses, not tested): few training trials "
  "per participant in protocol A, a coarse 16×16 grid for 22 electrodes, power features without phase/spatial-filter information, "
  "no hyper-parameter tuning for the CNN, strong between-participant differences in protocol B.")
w("")
tab = ROOT / "outputs" / "audit_v2" / "tables.md"
if tab.exists():
    w("## Additional experiments of the research audit (`outputs/audit_v2/`, exploratory)")
    w("")
    w("Generated by `scripts/make_audit_tables.py`. These runs did not change `final_v1`; interpretation, controls and caveats are in `docs/RESEARCH_AUDIT.md`. "
      "Euclidean alignment uses unlabeled data of the target participant (not zero-shot); every other row uses only training participants.")
    w("")
    w(tab.read_text(encoding="utf-8").replace("\n### ", "\n#### ").replace("### ", "#### ", 1))
    w("")
w("## Reproduce")
w("")
w("```bash")
w("python -m src.training.train evaluate --protocol cross_session loso --name final_v1 --status final")
w("python scripts/make_experiment_report.py final_v1")
w("```")
w("")
w("Seeds: `evaluation.seed` = 42 (+ participant ID for the CNN). Exact numerical reproducibility of the CNN can depend on the PyTorch version, "
  "CPU and thread count; classical models are deterministic given the data.")
w("")
w("## Configuration snapshot")
w("")
w("```json")
w(json.dumps(cfg, indent=1))
w("```")
(ROOT / "docs" / "EXPERIMENTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote docs/EXPERIMENTS.md")
